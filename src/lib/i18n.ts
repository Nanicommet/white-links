export type TranslateKey = keyof Dict;

export function translate(lang: Lang, key: TranslateKey): string {
  return dictionaries[lang][key] ?? dictionaries.fr[key] ?? key;
}

export const RTL_LANGS: Lang[] = ["ar"];
export function isRTL(lang: Lang): boolean {
  return RTL_LANGS.includes(lang);
}

// Format a date in Africa/Tunis timezone
export function formatDate(d: Date | string, lang: Lang = "fr"): string {
  const date = typeof d === "string" ? new Date(d) : d;
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-TN" : "fr-FR", {
    timeZone: "Africa/Tunis",
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}

export function formatTime(d: Date | string, lang: Lang = "fr"): string {
  const date = typeof d === "string" ? new Date(d) : d;
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-TN" : "fr-FR", {
    timeZone: "Africa/Tunis",
    timeStyle: "short",
  }).format(date);
}
